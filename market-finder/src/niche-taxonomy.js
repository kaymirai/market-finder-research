export const NICHE_TAXONOMY = Object.freeze(Object.fromEntries(
  Object.entries(TAXONOMY_SOURCE).map(([axisId, axis]) => [
    axisId,
    Object.freeze({
      id: axis.id,
      label: axis.label,
      terms: Object.freeze(uniqueTerms(axis.terms)),
    }),
  ]),
))

export function taxonomyTerms(axisId) {
  return [...(NICHE_TAXONOMY[axisId]?.terms ?? [])]
}

export function nextTaxonomyAxis(currentAxisId) {
  const currentIndex = NICHE_AXIS_ORDER.indexOf(currentAxisId)
  if (currentIndex < 0) return NICHE_AXIS_ORDER[0]
  return NICHE_AXIS_ORDER[(currentIndex + 1) % NICHE_AXIS_ORDER.length]
}
