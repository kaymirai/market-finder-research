const normalizeTerm = (value) => String(value ?? '')
  .toLowerCase()
  .replace(/[’']/g, '')
  .replace(/&/g, ' and ')
  .replace(/[^a-z0-9]+/g, ' ')
  .replace(/\s+/g, ' ')
  .trim()

const uniqueTerms = (terms) => [...new Set(terms.map(normalizeTerm).filter(Boolean))]

